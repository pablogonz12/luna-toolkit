local H = dofile((arg[0]:match("^(.*)/[^/]*$") or ".") .. "/rtlib.lua")
local json = require("json")
local cjson = require("cjson")
local safe = require("cjson.safe")
H.eq(json.encode({ a = 1, b = { 1, 2, 3 }, c = "x" }), '{"a":1,"b":[1,2,3],"c":"x"}', "encode")
H.eq(json.encode(json.array({})), "[]", "empty array")
H.eq(json.encode(json.empty_array), "[]", "empty_array marker")
H.eq(json.encode({}), "{}", "empty table is object")
H.eq(json.dumps, json.encode, "dumps alias")
H.eq(json.encode({ n = json.null }), '{"n":null}', "null")
H.eq(json.encode("a\"b\\c\n\t\1é"), '"a\\"b\\\\c\\n\\t\\u0001é"', "escape")
H.eq(json.encode(1.5), "1.5", "float")
H.eq(json.encode(3), "3", "int")
H.throws(function() json.encode(0/0) end, "nan")
H.throws(function() json.encode(function() end) end, "function")
local t = {}; t.t = t
H.throws(function() json.encode(t) end, "circular")
local d = json.decode('{"a":[1,2.5,-3e2,true,false,null],"s":"\\u00e9\\ud83d\\ude00\\n","o":{}}')
H.eq(d.a[1], 1, "int"); H.eq(d.a[2], 2.5, "float"); H.eq(d.a[3], -300, "exp")
H.eq(d.a[4], true, "t"); H.eq(d.a[5], false, "f"); H.eq(d.a[6], json.null, "null")
H.eq(d.s, "é😀\n", "unicode")
H.eq(next(d.o), nil, "empty obj")
H.eq(json.encode(json.decode("[]")), "[]", "empty roundtrip")
H.eq(json.encode(json.decode('  [ 1 , {"k" : "v"} ]  ')), '[1,{"k":"v"}]', "ws roundtrip")
for _, bad in ipairs({ "", "{", "[1,]", '{"a":}', "tru", "01", '"abc', '{"a":1} x', "[1 2]", '"\\ud800"', '"\\x"', "{1:2}", "-", "1." }) do
  H.throws(function() json.decode(bad) end, "bad: " .. bad)
end
H.throws(function() json.decode(nil) end, "non-string")
H.eq(cjson.decode("[1]")[1], 1, "cjson")
H.eq(cjson.null, json.null, "cjson.null")
cjson.encode_empty_table_as_object(false)
H.eq(cjson.encode(cjson.empty_array), "[]", "cjson empty")
local v, err = safe.decode("{bad")
H.eq(v, nil, "safe nil"); H.ok(type(err) == "string", "safe err")
H.eq(safe.encode({ 1 }), "[1]", "safe encode")
local big = {}
for i = 1, 1000 do big[i] = { id = i, name = "n" .. i } end
H.eq(#json.decode(json.encode(big)), 1000, "big")
H.done("rt_json")
