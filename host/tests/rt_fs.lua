local H = dofile((arg[0]:match("^(.*)/[^/]*$") or ".") .. "/rtlib.lua")
local fs, lfs, core = require("fs"), require("lfs"), require("luna_core")
local priv, utils, mill = require("privfs"), require("utils"), require("millennium")
local root = string.format("/tmp/luna-rt-fs-%d", core.getpid())
H.eq(fs.join("a", "b", "c"), "a/b/c", "join"); H.eq(fs.join("a/", "/b"), "/b", "join abs")
H.eq(fs.parent_path("/a/b/c"), "/a/b", "parent"); H.eq(fs.parent_path("/a"), "/", "parent root")
H.eq(fs.absolute("/a/./b/../c"), "/a/c", "absolute")
H.eq(fs.absolute("x"), fs.current_path() .. "/x", "absolute rel")
H.ok(fs.create_directories(root .. "/a/b/c"), "mkdirs")
H.ok(fs.create_directories(root .. "/a/b/c"), "mkdirs idempotent")
H.ok(fs.exists(root .. "/a/b/c"), "exists")
H.ok(fs.write(root .. "/a/f.txt", "hello"), "write")
H.eq(fs.read(root .. "/a/f.txt"), "hello", "read")
local l = fs.list(root .. "/a")
H.eq(#l, 2, "list n"); H.eq(l[1].name, "b", "list name"); H.eq(l[1].is_directory, true, "list dir")
H.eq(l[2].is_directory, false, "list file"); H.eq(l[2].path, root .. "/a/f.txt", "list path")
H.eq(#fs.list_recursive(root), 4, "list_recursive")
H.eq(lfs.attributes(root .. "/a/f.txt", "size"), 5, "lfs size")
H.eq(lfs.attributes(root .. "/a").mode, "directory", "lfs mode")
H.eq(lfs.attributes(root .. "/nope"), nil, "lfs missing")
local names = {}
for n in lfs.dir(root .. "/a") do names[#names + 1] = n end
H.eq(table.concat(names, ","), ".,..,b,f.txt", "lfs.dir")
H.ok(lfs.mkdir(root .. "/m"), "lfs mkdir"); H.ok(lfs.rmdir(root .. "/m"), "lfs rmdir")
H.ok(lfs.currentdir():sub(1, 1) == "/", "currentdir")
H.ok(priv.mkdir_private(root .. "/p"), "mkdir_private")
H.eq(core.stat(root .. "/p").perm, 448, "0700")
H.ok(priv.write_private(root .. "/p/s", "x"), "write_private")
H.eq(core.stat(root .. "/p/s").perm, 384, "0600")
H.ok(utils.write_json_atomic(root .. "/j.json", { a = 1 }), "atomic")
H.eq(utils.read_json(root .. "/j.json").a, 1, "read_json")
utils.write_json_atomic(root .. "/j.json", { a = 2 })
H.eq(utils.read_json(root .. "/j.json.bak").a, 1, "bak")
H.eq(utils.base64_encode("hello!!"), "aGVsbG8hIQ==", "b64")
H.eq(#core.urandom(16), 16, "urandom")
H.ok(core.gettime() > 1e9 and core.monotonic() > 0, "time")
H.eq(core.getpid() > 0, true, "pid")
H.ok(core.rename(root .. "/a/f.txt", root .. "/a/g.txt"), "rename")
H.ok(core.readlink("/proc/self/exe"), "readlink")
H.ok(fs.remove_all(root) > 0, "remove_all")
H.ok(not fs.exists(root), "gone")
H.eq(mill.version(), os.getenv("LUNA_VERSION") or "luna-dev", "version")
H.ok(mill.ready(), "ready")
mill.add_browser_js("a.js"); H.eq(mill.queued_js()[1], "a.js", "queue")
local pr = require("proc")
H.ok(pr.is_alive("luna-host"), "proc alive self")
H.ok(not pr.is_alive("definitely-not-a-proc"), "proc dead")
H.ok(pr.lib_mapped("luna-host", "libc"), "lib_mapped")
H.ok(not pr.lib_mapped("luna-host", "zzz-nonexistent-lib"), "lib not mapped")
H.done("rt_fs")
